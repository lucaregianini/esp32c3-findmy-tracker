#!/usr/bin/env python3
"""Generate main/keys.h from a go-haystack DEVICE.keys file.

Only the public advertisement keys go into the firmware. The private keys
never leave the Mac / Home Assistant.

Usage: python3 tools/gen_keys_h.py ~/Projects/go-haystack/NAME.keys
"""

import base64
import os
import sys
from pathlib import Path

if len(sys.argv) != 2:
    sys.exit("usage: gen_keys_h.py <path/to/NAME.keys>")
src = Path(sys.argv[1]).expanduser()
keys = []
for line in src.read_text().splitlines():
    if "Advertisement key" in line:
        k = base64.b64decode(line.split(":", 1)[1].strip())
        if len(k) != 28:
            sys.exit(f"bad key length {len(k)}")
        keys.append(k)
if not keys:
    sys.exit("no advertisement keys found")

rows = ",\n".join("    {" + ", ".join(f"0x{b:02x}" for b in k) + "}" for k in keys)
out = Path(__file__).resolve().parent.parent / "main" / "keys.h"
out.write_text(
    "// Generated by tools/gen_keys_h.py from " + src.name + ". Do not commit.\n"
    "#pragma once\n#include <stdint.h>\n\n"
    f"#define ADV_KEY_COUNT {len(keys)}\n\n"
    f"static const uint8_t ADV_KEYS[ADV_KEY_COUNT][28] = {{\n{rows}\n}};\n"
)
os.chmod(out, 0o600)
print(f"wrote {out} with {len(keys)} keys")
